# gen_section8.py: rewrites section 8 of docs/blueprints/library.md from
# docs/blueprints/library/features/*.wave.json, so the tables never drift from
# the data `scripts/waves check library` checks. Run from the repo root after
# editing that data: python3 docs/blueprints/library/gen_section8.py
import glob, json, os, re
DOC = "docs/blueprints/library.md"
def _feature(path):
    f = json.load(open(path))
    return {**f, "id": os.path.basename(path)[: -len(".wave.json")], "title": f["library_title"]}
F = sorted((_feature(p) for p in glob.glob("docs/blueprints/library/features/*.wave.json")),
           key=lambda f: (int(re.sub(r"\D", "", str(f["wave"]))), f.get("order", 0), f["id"]))
byid = {f["id"]: f for f in F}
issues = {33: ("Grid thumbnails by resampling", "p1"), 210: ("Import a folder", "p1"), 211: ("Rate, pick, reject with keys", "p1"),
          212: ("Keep the catalog across relaunch", "p1"), 32: ("Develop panel with histogram", "p1"),
          423: ("Render develop settings to pixels", "p1"), 424: ("Export JPEG at a set size", "p1"), 425: ("Crop and straighten", "p1"),
          426: ("Auto-advance", "p1"), 156: ("Loupe on a hidden photo after a collection switch", "p2 bug"),
          235: ("load renames a photo whose id a duplicate took", "p2 bug"), 724: ("Loupe rating keys and zoom", "p2"),
          31: ("Collections and filters", "p2"), 744: ("Keywords and camera details", "p2"), 427: ("Camera raw files", "p2"),
          185: ("Pro density inspector and status bar", "p3"), 291: ("16 controls without identifiers", "p3")}
how = {33: "whole issue", 210: "whole issue; its `LibraryCommands.swift` edit becomes the spine's File menu item plus `LibraryWindow+Import.swift`",
       211: "keys, Metadata menu, `cull(_:)` on ids, undo (`PhotoFlag` already landed in #750)",
       212: "whole issue; the file also carries `develop` and `crop` from the start", 32: "sliders, histogram, copy and paste",
       423: "render in loupe and grid; its catalog-file part is done by persist", 424: "whole issue", 425: "whole issue", 426: "whole issue",
       156: "fixed in `LibraryCatalog.swift` by the spine, or by open PR #217 if it merges first",
       235: "fixed in `uniquingIDs` by the spine (two passes, as the issue proposes)",
       724: "keys → cull; zoom, photo on the artboard, real size → loupe-viewport", 31: "not v1 (wave 5)", 744: "not v1 (wave 5)",
       427: "not v1 (wave 5, pending evidence)", 185: "status pills and inspector header; pulled into v1 (design.md requires the readout)",
       291: "what is left after each feature names its own controls; pulled into v1 (journeys need it)"}
waves = {1: "Wave 1: the spine (waits on nothing)", 2: "Wave 2: the loop on real files (after the spine)",
         3: "Wave 3: develop and the readouts (after wave 2)", 4: "Wave 4: crop and export (after develop)", 5: "Wave 5: after v1 (tier 2, not v1)"}
o = ["## 8. Coverage and waves\n\nThe data behind this section is `docs/blueprints/library/features/*.wave.json`;\n"
     "`scripts/waves check library` fails when two features in\n"
     "one wave own the same file (or one owns a folder or prefix holding the\n"
     "other's), when a feature depends on one in its own or a later wave, or\n"
     "when a Sources file is\n"
     "owned but missing from `c4-planned.json` (or the reverse). It prints\n"
     "`waves: OK`. The tables below are generated by\n"
     "`python3 docs/blueprints/library/gen_section8.py`.\n\n"
     "### 8.1 Coverage matrix: every open `line:library` issue\n\n"
     "| Issue | Title (short) | Tier | Feature | How |\n|---|---|---|---|---|\n"]
for n in sorted(issues):
    feats = [f["id"] for f in F if n in f["issues"]]
    v1 = all(byid[x]["wave"] < 5 for x in feats)
    o.append(f"| #{n} | {issues[n][0]} | {issues[n][1]} | {', '.join(feats) if v1 else 'not v1: ' + ', '.join(feats)} | {how[n]} |\n")
o.append("""
17 of 17 open issues are mapped. Nothing is dropped: the three "not v1"
issues have a wave-5 feature so their packets can follow v1 directly.

**Issue dependency lines to edit (captain).** The issues were filed as a
chain (#210 after #33, #211 after #210, #212 after #211, #423 after #212).
With the contracts and fakes in the spine, those features no longer wait on
each other: #33, #210, #211, #212 and #724's zoom all run in wave 2. Each
issue's `Depends on` line should read "the spine" (as `docs/priorities.md`
asks: fix the line, don't serialize the work). Their "Files likely
involved" lists are superseded by the owned files below; each packet says so.

### 8.2 Features

| Feature | Wave | What it delivers | Issues | Journeys | Quality ids (section 7) | Depends on (features) |
|---|---|---|---|---|---|---|
""")
for f in F:
    o.append(f"| `{f['id']}` | {f['wave']} | {f['title']} | {', '.join('#' + str(i) for i in f['issues'])} | "
             f"{', '.join(f['journeys']) or '–'} | {f.get('quality', '–')} | {', '.join('`' + x + '`' for x in f['depends']) or '–'} |\n")
o.append("""
### 8.3 Waves, owned files and what each waits on

A feature may touch only its owned files (paths from the repo root; a path
ending in `/` or `+` covers everything under or starting with it). In one
wave no two features share a file. A later wave may take a file an earlier
wave owned; the note says so.

""")
for w in sorted({f["wave"] for f in F}):
    o.append(f"#### {waves[w]}\n\n")
    for f in [x for x in F if x["wave"] == w]:
        o.append(f"**`{f['id']}`** ({', '.join('#' + str(i) for i in f['issues'])}). {f['title']}.\n\n")
        o.append(f"- Engine (creative-core): {f['core']}.\n- SuiteUI: {f['suiteui']}.\n")
        if f["notes"]:
            o.append(f"- Note: {f['notes']}\n")
        o.append("- Owned files: " + ", ".join("`" + p + "`" for p in f["owned"]) + ".\n\n")
o.append(open("docs/blueprints/library/section8-tail.md").read())
s = open(DOC).read()
a = s.index("## 8. Coverage and waves")
b = s.index("---\n\n## 9. Critic rounds")
open(DOC, "w").write(s[:a] + "".join(o) + "\n" + s[b:])
